grant select on public.divisions, public.districts, public.upazilas to anon, authenticated;
grant select on public.places, public.institutions, public.businesses, public.government_services to anon, authenticated;
grant select on public.public_blood_donors to anon, authenticated;
grant select, insert, update on public.blood_donors to authenticated;
grant select, insert, update on public.blood_requests to authenticated;
grant insert (division_id, district_id, upazila_id) on public.news to authenticated;
grant update (division_id, district_id, upazila_id) on public.news to authenticated;

drop policy if exists divisions_public_read on public.divisions;
create policy divisions_public_read on public.divisions for select using (true);
drop policy if exists districts_public_read on public.districts;
create policy districts_public_read on public.districts for select using (true);
drop policy if exists upazilas_public_read on public.upazilas;
create policy upazilas_public_read on public.upazilas for select using (true);

drop policy if exists places_published_read on public.places;
create policy places_published_read on public.places for select using (status = 'published');
drop policy if exists institutions_published_read on public.institutions;
create policy institutions_published_read on public.institutions for select using (status = 'published');
drop policy if exists businesses_published_read on public.businesses;
create policy businesses_published_read on public.businesses for select using (status = 'published');
drop policy if exists government_services_published_read on public.government_services;
create policy government_services_published_read on public.government_services for select using (status = 'published');

drop policy if exists blood_donors_self_read on public.blood_donors;
create policy blood_donors_self_read on public.blood_donors for select to authenticated using (user_id = auth.uid());
drop policy if exists blood_donors_self_insert on public.blood_donors;
create policy blood_donors_self_insert on public.blood_donors for insert to authenticated with check (user_id = auth.uid());
drop policy if exists blood_donors_self_update on public.blood_donors;
create policy blood_donors_self_update on public.blood_donors for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists blood_requests_public_active_read on public.blood_requests;
create policy blood_requests_public_active_read on public.blood_requests for select using (status = 'active');
drop policy if exists blood_requests_self_read on public.blood_requests;
create policy blood_requests_self_read on public.blood_requests for select to authenticated using (requester_id = auth.uid());
drop policy if exists blood_requests_self_insert on public.blood_requests;
create policy blood_requests_self_insert on public.blood_requests for insert to authenticated with check (requester_id = auth.uid());
drop policy if exists blood_requests_self_update on public.blood_requests;
create policy blood_requests_self_update on public.blood_requests for update to authenticated
  using (requester_id = auth.uid())
  with check (requester_id = auth.uid() and status = 'cancelled');
drop policy if exists blood_requests_staff_read on public.blood_requests;
create policy blood_requests_staff_read on public.blood_requests for select to authenticated
  using (public.is_current_user_staff());
drop policy if exists blood_requests_staff_update on public.blood_requests;
create policy blood_requests_staff_update on public.blood_requests for update to authenticated
  using (public.is_current_user_staff())
  with check (public.is_current_user_staff());

