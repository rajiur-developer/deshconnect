-- Restore the schema required by the site's location and directory filters.
-- Location keys intentionally use text because the app's stable IDs are slugs
-- (for example, div-dhaka), not PostgreSQL UUIDs.

create table if not exists public.divisions (
  id text primary key,
  slug text not null unique,
  name text not null,
  capital text,
  districts_count integer not null default 0,
  summary text,
  image text
);

create table if not exists public.districts (
  id text primary key,
  slug text not null unique,
  name text not null,
  division_id text not null references public.divisions(id) on delete cascade,
  summary text,
  image text
);

create table if not exists public.upazilas (
  id text primary key,
  slug text not null,
  name text not null,
  district_id text not null references public.districts(id) on delete cascade,
  image text,
  summary text,
  unique (district_id, slug)
);

-- Convert the existing UUID-typed profile location fields without changing
-- their stored values. New app IDs and all new location values are text.
drop view if exists public.public_profiles;
alter table public.profiles
  alter column division_id type text using division_id::text,
  alter column district_id type text using district_id::text,
  alter column upazila_id type text using upazila_id::text;
create or replace view public.public_profiles as
  select id, username, full_name, avatar, bio, division_id, district_id,
         upazila_id, created_at, avatar_key
  from public.profiles;
grant select on public.public_profiles to anon, authenticated;

alter table public.news
  add column if not exists division_id text,
  add column if not exists district_id text,
  add column if not exists upazila_id text;

create table if not exists public.places (
  id uuid primary key default gen_random_uuid(), slug text not null unique,
  name text not null, category text not null, summary text not null,
  description text not null, address text not null, latitude float8,
  longitude float8, image text not null, gallery text[] default '{}',
  rating float4 default 0, review_count integer default 0,
  opening_hours text, entry_fee text, best_time text,
  verification text not null default 'unverified', source text,
  division_id text references public.divisions(id),
  district_id text references public.districts(id),
  upazila_id text references public.upazilas(id),
  status text not null default 'published', last_checked_at timestamptz default now(),
  created_at timestamptz default now(), updated_at timestamptz default now()
);

create table if not exists public.institutions (
  id uuid primary key default gen_random_uuid(), slug text not null unique,
  name text not null, category text not null, description text not null,
  address text not null, phone text, email text, website text,
  emergency_phone text, latitude float8, longitude float8, image text not null,
  verification text not null default 'unverified', source text,
  division_id text references public.divisions(id),
  district_id text references public.districts(id),
  upazila_id text references public.upazilas(id),
  status text not null default 'published', last_checked_at timestamptz default now(),
  created_at timestamptz default now(), updated_at timestamptz default now()
);

create table if not exists public.businesses (
  id uuid primary key default gen_random_uuid(), slug text not null unique,
  name text not null, category text not null, description text not null,
  address text not null, phone text, website text, image text not null,
  verification text not null default 'unverified',
  division_id text references public.divisions(id),
  district_id text references public.districts(id),
  upazila_id text references public.upazilas(id),
  status text not null default 'published',
  created_at timestamptz default now(), updated_at timestamptz default now()
);

create table if not exists public.government_services (
  id uuid primary key default gen_random_uuid(), slug text not null unique,
  name text not null, category text not null, description text not null,
  office_address text not null, phone text, emergency_phone text, website text,
  hours text, required_documents text[] default '{}',
  verification text not null default 'unverified',
  division_id text references public.divisions(id),
  district_id text references public.districts(id),
  upazila_id text references public.upazilas(id),
  status text not null default 'published',
  created_at timestamptz default now(), updated_at timestamptz default now()
);

create table if not exists public.blood_donors (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  blood_group text not null, availability text not null default 'available',
  preferred_contact text not null default 'phone', contact_value text not null,
  phone text, whatsapp text, last_donation_at date, donation_count integer default 0,
  notes text, consent_listed boolean default false, consent_contact boolean default false,
  consent_expiry timestamptz not null,
  division_id text references public.divisions(id),
  district_id text references public.districts(id),
  upazila_id text references public.upazilas(id),
  created_at timestamptz default now(), updated_at timestamptz default now()
);

create table if not exists public.blood_requests (
  id uuid primary key default gen_random_uuid(),
  requester_id uuid not null references public.profiles(id) on delete cascade,
  blood_group text not null, units integer not null check (units between 1 and 20),
  patient text, hospital text not null, needed_by date not null, notes text,
  status text not null default 'under_review',
  division_id text references public.divisions(id),
  district_id text references public.districts(id),
  upazila_id text references public.upazilas(id),
  created_at timestamptz default now(), updated_at timestamptz default now()
);

create or replace view public.public_blood_donors as
select id, user_id, blood_group, availability, preferred_contact, donation_count,
       consent_listed, division_id, district_id, upazila_id, created_at, updated_at
from public.blood_donors
where consent_listed = true and consent_expiry >= now();

create index if not exists places_location_idx on public.places (division_id, district_id, upazila_id);
create index if not exists institutions_location_idx on public.institutions (division_id, district_id, upazila_id);
create index if not exists businesses_location_idx on public.businesses (division_id, district_id, upazila_id);
create index if not exists government_services_location_idx on public.government_services (division_id, district_id, upazila_id);
create index if not exists news_location_idx on public.news (division_id, district_id, upazila_id);
create index if not exists blood_donors_location_idx on public.blood_donors (division_id, district_id, upazila_id, blood_group);
create index if not exists blood_requests_location_idx on public.blood_requests (division_id, district_id, upazila_id, blood_group, status);

